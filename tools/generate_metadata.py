#!/usr/bin/env python3
"""Generate and validate BoostPack's version-pinned, embedded Boost metadata.

This is a maintainer-only tool; consumers need only BoostPack.cmake and CMake.
Uses Python's standard library, the Boost release superproject Git tree and
each module's upstream CMakeLists.txt (not mutable branch-head metadata).
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import configparser
import difflib
import json
import os
from pathlib import Path
import re
import sys
import time
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parent.parent
BOOST_VERSION = "1.92.0"
MANIFEST = ROOT / "tools" / f"boost-{BOOST_VERSION}.json"
SELECTION = ROOT / "tools" / "modules.txt"
MODULE = ROOT / "cmake" / "BoostPack.cmake"
START = f"  # BEGIN GENERATED BOOST {BOOST_VERSION} METADATA"
END = f"  # END GENERATED BOOST {BOOST_VERSION} METADATA"
IDENTIFIER = re.compile(r"[a-z][a-z0-9_]*\Z")
REVISION = re.compile(r"[0-9a-f]{40}\Z")
REFERENCE = re.compile(r"Boost::([a-z][a-z0-9_]*)")


def download(url: str) -> str:
    headers = {"User-Agent": "BoostPack-metadata-generator", "Accept": "application/vnd.github+json"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        headers["Authorization"] = f"Bearer {token}"
    last_error = None
    for attempt in range(3):
        try:
            with urlopen(Request(url, headers=headers), timeout=30) as response:
                return response.read().decode("utf-8")
        except (HTTPError, URLError, TimeoutError) as exc:
            last_error = exc
            if isinstance(exc, HTTPError) and exc.code in (401, 403, 404):
                break
            time.sleep(attempt + 1)
    raise RuntimeError(f"Cannot fetch {url}: {last_error}") from last_error


def selected_modules() -> list[str]:
    roots = [
        line.strip()
        for line in SELECTION.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if not roots or len(roots) != len(set(roots)) or any(not IDENTIFIER.fullmatch(x) for x in roots):
        raise ValueError("tools/modules.txt must contain unique valid Boost module names")
    return sorted(roots)


def validate(manifest: dict, roots: list[str]) -> None:
    if manifest.get("boost_version") != BOOST_VERSION:
        raise ValueError(f"Expected Boost {BOOST_VERSION}")
    modules = manifest.get("modules")
    if not isinstance(modules, dict) or not modules:
        raise ValueError("Manifest must contain a nonempty 'modules' mapping")
    for name, data in modules.items():
        if not IDENTIFIER.fullmatch(name) or not isinstance(data, dict):
            raise ValueError(f"Invalid module entry: {name}")
        if not REVISION.fullmatch(data.get("sha", "")):
            raise ValueError(f"Invalid pinned SHA for {name}")
        deps = data.get("dependencies")
        if not isinstance(deps, list) or deps != sorted(set(deps)):
            raise ValueError(f"Invalid or unsorted dependency list for {name}")
        for dep in deps:
            if dep not in modules or dep == name:
                raise ValueError(f"Missing or self-referential dependency: {name} -> {dep}")

    # Validate the dependency DAG before CMake attempts target registration.
    state = {}

    def visit(name: str) -> None:
        if state.get(name) == 1:
            raise ValueError(f"Cyclic module dependencies involving {name}")
        if state.get(name) == 2:
            return
        state[name] = 1
        for dep in modules[name]["dependencies"]:
            visit(dep)
        state[name] = 2

    for name in modules:
        visit(name)

    # The generated set must be precisely the closure of requested roots.
    closure = set()
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name in closure:
            continue
        if name not in modules:
            raise ValueError(f"Requested module absent from manifest: {name}")
        closure.add(name)
        pending.extend(modules[name]["dependencies"])
    if closure != set(modules):
        raise ValueError(f"Orphaned manifest modules: {sorted(set(modules) - closure)}")


def render(manifest: dict) -> str:
    modules = manifest["modules"]
    lines = [START, "  # Generated by tools/generate_metadata.py. Do not edit by hand."]
    for name in sorted(modules):
        deps = modules[name]["dependencies"]
        lines.append(f'  set(_bp_deps_{name} {" ".join(deps) if deps else chr(34) + chr(34)})')
    lines.append("")
    for name in sorted(modules):
        lines.append(f'  set(_bp_sha_{name} {modules[name]["sha"]})')
    lines.append(END)
    return "\n".join(lines)


def embed(manifest: dict, check: bool) -> None:
    source = MODULE.read_text(encoding="utf-8")
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError("Expected exactly one generated metadata block")
    before, rest = source.split(START, 1)
    _, after = rest.split(END, 1)
    updated = before + render(manifest) + after
    if check:
        if updated != source:
            raise ValueError("BoostPack.cmake is out of sync; run: python tools/generate_metadata.py --refresh")
    else:
        MODULE.write_text(updated, encoding="utf-8")


def upstream_manifest(roots: list[str]) -> dict:
    base = f"https://raw.githubusercontent.com/boostorg/boost/boost-{BOOST_VERSION}"
    tree_url = f"https://api.github.com/repos/boostorg/boost/git/trees/boost-{BOOST_VERSION}?recursive=1"
    tree = json.loads(download(tree_url))
    if tree.get("truncated"):
        raise ValueError("Upstream superproject Git tree was truncated")

    gitmodules = configparser.RawConfigParser()
    gitmodules.read_string(download(f"{base}/.gitmodules"))
    paths = {}
    for section in gitmodules.sections():
        path = gitmodules.get(section, "path")
        if path.startswith("libs/"):
            remote = gitmodules.get(section, "url")
            slug = remote.rsplit("/", 1)[-1].removesuffix(".git")
            paths[path] = slug
    revisions = {
        item["path"]: item["sha"]
        for item in tree["tree"]
        if item["type"] == "commit" and item["path"] in paths
    }
    modules = {slug: revisions[path] for path, slug in paths.items() if path in revisions}
    if len(modules) != len(revisions):
        raise ValueError("Ambiguous Boost submodule names")

    def fetch_module(name: str) -> tuple[str, dict]:
        sha = modules.get(name)
        if not sha:
            raise ValueError(f"'{name}' is not a submodule of Boost {BOOST_VERSION}")
        cmake = download(f"https://raw.githubusercontent.com/boostorg/{name}/{sha}/CMakeLists.txt")
        # Strip line comments. Unknown Boost::* names can be local targets
        # (for example, Boost::asio_core), not separate Git repositories.
        cmake = re.sub(r"(?m)^[ \t]*#.*$", "", cmake)
        deps = sorted({
            dep for dep in REFERENCE.findall(cmake)
            if dep != name and dep in modules
        })
        return name, {"sha": sha, "dependencies": deps}

    discovered = {}
    queue = set(roots)
    while queue:
        batch = sorted(queue - set(discovered))
        if not batch:
            break
        with ThreadPoolExecutor(max_workers=8) as executor:
            for name, info in executor.map(fetch_module, batch):
                discovered[name] = info
                queue.update(info["dependencies"])
        queue.difference_update(discovered)

    result = {"boost_version": BOOST_VERSION, "modules": dict(sorted(discovered.items()))}
    validate(result, roots)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--refresh", action="store_true", help="Fetch upstream metadata and write both generated files")
    mode.add_argument("--verify-upstream", action="store_true", help="Check committed metadata against upstream Boost release")
    mode.add_argument("--check", action="store_true", help="Offline consistency check (default)")
    args = parser.parse_args()
    roots = selected_modules()
    if args.refresh:
        upstream = upstream_manifest(roots)
        MANIFEST.write_text(json.dumps(upstream, indent=2) + "\n", encoding="utf-8")
        embed(upstream, check=False)
        print(f"Regenerated {len(upstream['modules'])} Boost {BOOST_VERSION} modules")
        return

    committed = json.loads(MANIFEST.read_text(encoding="utf-8"))
    validate(committed, roots)
    if args.verify_upstream:
        upstream = upstream_manifest(roots)
        if upstream != committed:
            expected = json.dumps(upstream, indent=2).splitlines()
            actual = json.dumps(committed, indent=2).splitlines()
            print("\n".join(difflib.unified_diff(actual, expected, fromfile="committed", tofile="upstream")), file=sys.stderr)
            raise ValueError("Committed Boost metadata differs from upstream")
    embed(committed, check=True)
    print(f"Verified {len(committed['modules'])} Boost {BOOST_VERSION} modules")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, ValueError, OSError, json.JSONDecodeError) as exc:
        sys.exit(f"BoostPack metadata: {exc}")
